def get_card_rarity(card: dict) -> str:
    """Определяет редкость карты профессии по полезности и сложности."""
    name = str(card.get("name", "")).lower()
    tag = card.get("tag", "")
    if any(x in name for x in ["хирург", "нейрохирург", "учёный", "ученый", "пилот", "военный инженер"]):
        return "legendary"
    if tag in ("medicine", "engineering", "science"):
        return "rare"
    if tag in ("tech", "security", "agriculture", "construction"):
        return "uncommon"
    return "common"


