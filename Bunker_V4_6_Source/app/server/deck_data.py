def apply_advanced_synergies(cards: dict) -> list:
    """Создаёт спорные ситуации без оценки персонажа."""
    result = []
    all_text = " ".join(
        str(card.get("value", ""))
        for card in cards.values()
        if isinstance(card, dict)
    ).lower()

    for rule in ADVANCED_SYNERGY_RULES:
        if any(word in all_text for word in rule["when_keywords"]):
            result.append({
                "id": rule["id"],
                "title": rule["title"],
                "effect": rule["effect"]
            })
    return result

