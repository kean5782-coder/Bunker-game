def apply_character_synergies(cards: dict) -> list:
    """Возвращает найденные игровые конфликты и преимущества."""
    found = []
    profession = cards.get("profession", {})
    health = cards.get("health", {})
    trait = cards.get("trait", {})

    text_health = str(health.get("value", "")).lower()
    text_trait = str(trait.get("value", "")).lower()

    for rule in SYNERGY_RULES:
        if rule.get("when_profession_tags") and profession.get("tag") not in rule["when_profession_tags"]:
            continue
        if rule.get("when_health_keywords") and not any(k in text_health for k in rule["when_health_keywords"]):
            continue
        if rule.get("when_traits_keywords") and not any(k in text_trait for k in rule["when_traits_keywords"]):
            continue
        found.append({
            "id": rule["id"],
            "title": rule["title"],
            "effect": rule["effect"]
        })
    return found


