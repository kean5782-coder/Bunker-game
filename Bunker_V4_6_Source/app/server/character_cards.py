"""Hand-written character deck. Each line is a card, with explicit game effects.

Format: name | description | properties. s = skill, t = trait, r = risk,
p = protection. An empty property list is intentional: a prop can be just a prop.
Descriptions never determine mechanics. Keep the two consistent when editing.
"""
import hashlib


CARD_EFFECTS = {}


def _pool(category, text):
    rows = []
    effects = CARD_EFFECTS.setdefault(category, {})
    for line in text.strip().splitlines():
        name, desc, properties = (part.strip() for part in line.split('|'))
        if name in effects:
            raise ValueError(f'Duplicate {category} card: {name}')
        effect = {'id': category + '_' + hashlib.sha256(name.encode()).hexdigest()[:12],
                  'skills': {}, 'traits': [], 'risks': [], 'protection': []}
        row = {'name': name, 'desc': desc}
        for prop in properties.split():
            kind, value = prop.split(':', 1)
            if kind == 's':
                skill, strength = value.split('=')
                effect['skills'][skill] = float(strength)
            elif kind in ('t', 'r', 'p'):
                effect[{'t': 'traits', 'r': 'risks', 'p': 'protection'}[kind]].append(value)
            elif kind in ('tag', 'severity'):
                row[kind] = value
            else:
                raise ValueError(f'Unknown card property: {prop}')
        effect['roleplay_only'] = not any(effect[k] for k in ('skills', 'traits', 'risks', 'protection'))
        rows.append(row)
        effects[name] = effect
    return rows


