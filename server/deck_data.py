def generate_game_deck(player_count: Optional[int] = None, bunker_capacity: Optional[int] = None, enable_traitor: bool = False, num_players: Optional[int] = None):
    """
    Генерирует уникальный набор карт для новой игры.
    Если enable_traitor == True, одному случайному игроку выдается секретная роль Предателя.
    """
    if player_count is None:
        player_count = num_players if num_players is not None else 6

    if bunker_capacity is None:
        bunker_capacity = max(1, player_count // 2)

    catastrophe = random.choice(CATASTROPHES)
    bunker_base = random.choice(BUNKER_PRESETS)

    raw_fac = bunker_base.get("facilities", [])
    fac_list = list(raw_fac) if isinstance(raw_fac, (list, tuple)) else []

    bunker = {
        "name": bunker_base.get("name", "Бункер «Убежище»"),
        "size_sqm": bunker_base["size_sqm"],
        "description": bunker_base["description"],
        "facilities": fac_list,
        "threat": bunker_base["threat"],
        "supplies_years": bunker_base["supplies_years"],
        "capacity": bunker_capacity,
        "initial_capacity": bunker_capacity,
        "threat_fixed": False
    }

    # 1. Сбалансированная подборка профессий:
    # Гарантируем минимум 1 медицину и 1 инженерию/технику/науку
    # Ограничиваем бесполезные/шуточные профессии до максимум 25-30%
    med_profs = [p for p in PROFESSIONS if p.get("tag") == "medicine"]
    eng_profs = [p for p in PROFESSIONS if p.get("tag") in ("engineering", "science", "tech")]
    useful_other = [p for p in PROFESSIONS if p.get("tag") in ("agriculture", "food", "security", "craft", "education", "social", "logistics", "transport")]
    useless_profs = [p for p in PROFESSIONS if p.get("tag") == "useless"]

    selected_profs = []
    # Минимум 1 медик
    if med_profs:
        selected_profs.append(random.choice(med_profs))
    # Минимум 1 инженер / техник
    avail_eng = [p for p in eng_profs if p not in selected_profs]
    if avail_eng:
        selected_profs.append(random.choice(avail_eng))

    # Максимум бесполезных профессий (для 6 игроков — максимум 1, для 8-10 — максимум 2)
    max_useless = max(1, int(player_count * 0.25)) if player_count >= 4 else 0
    num_useless = random.randint(0, min(max_useless, len(useless_profs)))
    if num_useless > 0:
        selected_profs.extend(random.sample(useless_profs, num_useless))

    # Добираем оставшиеся слоты из полезных профессий
    remaining_pool = [p for p in (med_profs + eng_profs + useful_other) if p not in selected_profs]
    needed_profs = player_count - len(selected_profs)
    if needed_profs > 0:
        selected_profs.extend(random.sample(remaining_pool, min(needed_profs, len(remaining_pool))))

    # Если всё ещё не хватает
    if len(selected_profs) < player_count:
        leftover = [p for p in PROFESSIONS if p not in selected_profs]
        selected_profs.extend(random.sample(leftover, player_count - len(selected_profs)))

    random.shuffle(selected_profs)
    professions = selected_profs

    # 2. Сбалансированная подборка здоровья:
    # 25% good, 35% minor, 25% medium, 15% critical
    h_good = [h for h in HEALTH_CONDITIONS if h.get("severity") == "good"]
    h_minor = [h for h in HEALTH_CONDITIONS if h.get("severity") == "minor"]
    h_medium = [h for h in HEALTH_CONDITIONS if h.get("severity") == "medium"]
    h_critical = [h for h in HEALTH_CONDITIONS if h.get("severity") == "critical"]

    c_good = max(1, round(player_count * 0.25))
    c_critical = max(1, round(player_count * 0.15))
    c_medium = max(1, round(player_count * 0.25))
    c_minor = max(1, player_count - c_good - c_critical - c_medium)

    selected_healths = []
    selected_healths.extend(random.sample(h_good, min(c_good, len(h_good))))
    selected_healths.extend(random.sample(h_minor, min(c_minor, len(h_minor))))
    selected_healths.extend(random.sample(h_medium, min(c_medium, len(h_medium))))
    selected_healths.extend(random.sample(h_critical, min(c_critical, len(h_critical))))

    # Добор до player_count при расхождении округлений
    while len(selected_healths) < player_count:
        rem = [h for h in HEALTH_CONDITIONS if h not in selected_healths]
        selected_healths.append(random.choice(rem if rem else HEALTH_CONDITIONS))
    selected_healths = selected_healths[:player_count]
    random.shuffle(selected_healths)
    healths = selected_healths

