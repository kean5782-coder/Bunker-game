def draw_random_event(catastrophe_id: str, used_ids: Optional[List[str]] = None) -> Optional[dict]:
    """
    Выбирает случайное событие, которое:
    1. Не использовалось ранее в игре (если возможно)
    2. СТРОГО СОВМЕСТИМО с текущим катаклизмом (ALL или катастрофа в compatible_catastrophes)
    """
    used = set(used_ids or [])
    compatible = []
    for ev in BUNKER_EVENTS:
        cats = ev.get("compatible_catastrophes")
        if isinstance(cats, list) and ("ALL" in cats or catastrophe_id in cats):
            compatible.append(ev)

    if not compatible:
        compatible = BUNKER_EVENTS

    # Сначала пробуем неиспользованные
    fresh = [ev for ev in compatible if ev["id"] not in used]
    pool = fresh if fresh else compatible
    return random.choice(pool) if pool else None

def calculate_event_odds(
    event: dict, 
    alive_players: list, 
    eliminated_players: list, 
    volunteer_id: Optional[str] = None,
    catastrophe: Optional[dict] = None,
    pity_bonus: int = 0,
    special_bonus: int = 0,
    sabotage_suppressed: bool = False
) -> dict:
    """
    Рассчитывает шансы разрешения испытания на основе ТОЛЬКО ОТКРЫТЫХ характеристик.
    Для BUNKER_CRISIS: суммирует бонусы и штрафы открытых карт живых игроков.
    Для SURFACE_EVENT: доброволец бункера повышает шанс, а озлобленные выжившие изгнанники снаружи САБОТИРУЮТ и снижают шанс!
    """
    ev_type = event.get("type", "BUNKER_CRISIS")
    raw_base = event.get("base_chance", 35)
    base_chance = max(20, min(35, int(raw_base * 0.55)))

    positive_factors = []
    negative_factors = []

    rules = event.get("rules", {})
    pos_rules = rules.get("positive", [])
    neg_rules = rules.get("negative", [])

    def _get_card_full_text(c):
        if not isinstance(c, dict):
            return ""
        return f"{c.get('value', '')} {c.get('details', '')} {c.get('desc', '')} {c.get('name', '')} {c.get('label', '')}".lower()

    def _eval_player_against_rules(player_data, rules_list, is_positive: bool):
        p_id, p_name, p_cards, _ = player_data
        matched_factors = []

        for rule in rules_list:
            r_type = rule.get("type")
            raw_val = rule.get("bonus" if is_positive else "penalty", 10)
            bonus = max(6, min(16, int(raw_val * 0.60))) if is_positive else max(8, min(16, int(raw_val * 0.65)))
            reason_tpl = rule.get("reason", "{player}")

            # 1. Багаж и Инвентарь (ТОЛЬКО ОТКРЫТЫЙ)
            if r_type == "baggage_kw":
                matched = False
                for bag_cat in ("big_inventory", "backpack", "baggage"):
                    bag = p_cards.get(bag_cat, {})
                    if bag.get("revealed", False):
                        text = _get_card_full_text(bag)
                        if any(kw in text for kw in rule.get("keywords", [])):
                            matched_factors.append({
                                "player_id": p_id,
                                "player_name": p_name,
                                "title": reason_tpl.replace("{player}", p_name),
                                "card_name": bag.get("value", "Инвентарь"),
                                "delta": bonus if is_positive else -bonus
                            })
                            matched = True
                            break
                if matched:
                    continue

            # 2. Профессия (ТОЛЬКО ОТКРЫТАЯ)
            elif r_type == "profession_tag":
                prof = p_cards.get("profession", {})
                if prof.get("revealed", False):
                    p_tag = prof.get("tag", "")
                    if p_tag in rule.get("tags", []):
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": prof.get("value", "Профессия"),
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

            elif r_type == "profession_kw":
                prof = p_cards.get("profession", {})
                if prof.get("revealed", False):
                    text = _get_card_full_text(prof)
                    if any(kw in text for kw in rule.get("keywords", [])):
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": prof.get("value", "Профессия"),
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

            # 3. Хобби (ТОЛЬКО ОТКРЫТОЕ)
            elif r_type == "hobby_kw":
                hobby = p_cards.get("hobby", {})
                if hobby.get("revealed", False):
                    text = _get_card_full_text(hobby)
                    if any(kw in text for kw in rule.get("keywords", [])):
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": hobby.get("value", "Хобби"),
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

            # 4. Факты (ТОЛЬКО ОТКРЫТЫЕ)
            elif r_type == "fact_kw":
                fact = p_cards.get("fact", {})
                if fact.get("revealed", False):
                    text = _get_card_full_text(fact)
                    if any(kw in text for kw in rule.get("keywords", [])):
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": fact.get("value", "Факт"),
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

            # 5. Здоровье (ТОЛЬКО ОТКРЫТОЕ)
            elif r_type == "health_kw":
                health = p_cards.get("health", {})
                if health.get("revealed", False):
                    text = _get_card_full_text(health)
                    if any(kw in text for kw in rule.get("keywords", [])):
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": health.get("value", "Здоровье"),
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

            # 6. Возраст / Биология / Пол (ТОЛЬКО ОТКРЫТАЯ)
            elif r_type == "age_range":
                bio = p_cards.get("gender") or p_cards.get("biology", {})
                if bio.get("revealed", False):
                    age = bio.get("age", 30)
                    min_age = rule.get("min", 0)
                    max_age = rule.get("max", 120)
                    if min_age <= age <= max_age:
                        matched_factors.append({
                            "player_id": p_id,
                            "player_name": p_name,
                            "title": reason_tpl.replace("{player}", p_name),
                            "card_name": f"Возраст: {age} лет",
                            "delta": bonus if is_positive else -bonus
                        })
                        continue

        # Ролевое соответствие (success_roles события)
        if is_positive and event.get("success_roles"):
            prof = p_cards.get("profession", {})
            if prof.get("revealed", False):
                p_tag = prof.get("tag", "")
                p_text = _get_card_full_text(prof)
                role_kw_map = {
                    "transport": ["водитель", "шофер", "пилот", "машинист", "дальнобойщик", "тракторист", "капитан", "транспорт", "штурман", "механик"],
                    "engineering": ["инженер", "механик", "электрик", "энергетик", "слесарь", "техник", "сварщик", "строитель", "монтажник", "техника безопасности"],
                    "craft": ["слесарь", "токарь", "плотник", "кузнец", "мастер", "ремонтник", "сварщик", "строитель"],
                    "medicine": ["врач", "хирург", "терапевт", "фельдшер", "медсестра", "фармацевт", "реаниматолог", "провизор", "эпидемиолог"],
                    "science": ["ученый", "химик", "биолог", "физик", "эколог", "лаборант", "исследователь", "геолог"],
                    "security": ["военный", "офицер", "полицейский", "спасатель", "мчс", "охранник", "боец", "снайпер", "сапер", "разведчик"],
                    "tech": ["программист", "радист", "электронщик", "робототехник", "связист", "системный"],
                    "food": ["повар", "технолог", "кулинар", "пекарь", "заготовщик", "кладовщик"],
                    "agriculture": ["агроном", "фермер", "животновод", "селекционер", "гидропоник"]
                }
                for role in event.get("success_roles", []):
                    if p_tag == role or any(kw in p_text for kw in role_kw_map.get(role, [])):
                        if not any(f.get("is_role") for f in matched_factors):
                            matched_factors.append({
                                "player_id": p_id,
                                "player_name": p_name,
                                "title": f"Профессиональная специфика ({role}): {prof.get('value')} ({p_name})",
                                "card_name": prof.get("value", "Профессия"),
                                "delta": 15,
                                "is_role": True
                            })
                            break

        # Универсальные синергии снаряжения для вылазок на поверхность
        if ev_type == "SURFACE_EVENT" and is_positive:
            # 1. Защитная экипировка от агрессивной среды (радиация, мороз, токсины)
            prot_kws = ["хим-радиационн", "химзащит", "озк", "противогаз", "респиратор", "ип-4", "скафандр", "дозиметр", "теплая", "зимн", "термобелье", "пуховик", "защитный"]
            for c_key in ("big_inventory", "backpack", "baggage"):
                c = p_cards.get(c_key, {})
                if c.get("revealed", False):
                    c_txt = _get_card_full_text(c)
                    if any(kw in c_txt for kw in prot_kws):
                        if not any("Защитная экипировка" in f["title"] for f in matched_factors):
                            matched_factors.append({
                                "player_id": p_id,
                                "player_name": p_name,
                                "title": f"Защитная экипировка от среды поверхности ({p_name})",
                                "card_name": c.get("value", "Защита"),
                                "delta": 16
                            })
                            break

            # 2. Экспедиционное снаряжение и приборы
            tool_kws = ["фонарь", "динамо", "солнечн", "батаре", "рация", "навигатор", "мультитул", "канистр", "шланг", "инструмент", "насос", "трос", "компас"]
            for c_key in ("big_inventory", "backpack", "baggage"):
                c = p_cards.get(c_key, {})
                if c.get("revealed", False):
                    c_txt = _get_card_full_text(c)
                    if any(kw in c_txt for kw in tool_kws):
                        if not any("Экспедиционное снаряжение" in f["title"] for f in matched_factors):
                            matched_factors.append({
                                "player_id": p_id,
                                "player_name": p_name,
                                "title": f"Экспедиционное снаряжение и приборы ({p_name})",
                                "card_name": c.get("value", "Снаряжение"),
                                "delta": 12
                            })
                            break

            # 3. Квалификация по технике безопасности и опасным производствам
            safety_kws = ["техника безопасности", "химкомбинат", "инженер", "ликвидатор", "спасатель", "водитель", "механик", "дальнобойщик", "автослесарь"]
            for c_key in ("profession", "fact", "hobby"):
                c = p_cards.get(c_key, {})
                if c.get("revealed", False):
                    c_txt = _get_card_full_text(c)
                    if any(kw in c_txt for kw in safety_kws):
                        if not any("Техника безопасности" in f["title"] for f in matched_factors):
                            matched_factors.append({
                                "player_id": p_id,
                                "player_name": p_name,
                                "title": f"Техника безопасности и спецквалификация ({p_name})",
                                "card_name": c.get("value", "Квалификация"),
                                "delta": 14
                            })
                            break

        return matched_factors

    # --- ЛОГИКА ДЛЯ BUNKER_CRISIS ---
    if ev_type == "BUNKER_CRISIS":
        for p in alive_players:
            p_data = _extract_player_data(p)
            positive_factors.extend(_eval_player_against_rules(p_data, pos_rules, is_positive=True))
            negative_factors.extend(_eval_player_against_rules(p_data, neg_rules, is_positive=False))

        if special_bonus > 0:
            spec_factor = {
                "player_id": "bunker",
                "player_name": "Бункер",
                "title": f"⚡ Спецкарта: технологический форсаж (+{special_bonus}%)",
                "card_name": "Спецспособность",
                "delta": special_bonus
            }
            positive_factors.append(spec_factor)

        pos_sum = sum(f["delta"] for f in positive_factors)
        neg_sum = sum(abs(f["delta"]) for f in negative_factors)
        final_chance = max(10, min(95, base_chance + pos_sum - neg_sum + pity_bonus))

        return {
            "type": "BUNKER_CRISIS",
            "base_chance": base_chance,
            "final_chance": final_chance,
            "positive_factors": positive_factors,
            "negative_factors": negative_factors,
            "volunteer": None,
            "exiles": []
        }

    # --- ЛОГИКА ДЛЯ SURFACE_EVENT (ВЫЛАЗКА И ДУЭЛЬ С ИЗГНАННИКАМИ) ---
    else:
        volunteer = None
        if volunteer_id:
            for p in alive_players:
                p_id, _, _, _ = _extract_player_data(p)
                if p_id == volunteer_id:
                    volunteer = p
                    break

        if not volunteer and alive_players:
            best_p = alive_players[0]
            best_score = -999
            for p in alive_players:
                p_data = _extract_player_data(p)
                pos = _eval_player_against_rules(p_data, pos_rules, is_positive=True)
                neg = _eval_player_against_rules(p_data, neg_rules, is_positive=False)
                sc = sum(f["delta"] for f in pos) - sum(abs(f["delta"]) for f in neg)
                if sc > best_score:
                    best_score = sc
                    best_p = p
            volunteer = best_p

        vol_data = _extract_player_data(volunteer) if volunteer else None
        vol_factors = []
        if vol_data:
            vol_factors.extend(_eval_player_against_rules(vol_data, pos_rules, is_positive=True))
            vol_factors.extend(_eval_player_against_rules(vol_data, neg_rules, is_positive=False))

        if special_bonus > 0:
            spec_factor = {
                "player_id": "bunker",
                "player_name": "Бункер",
                "title": f"⚡ Спецкарта: технологическое преимущество (+{special_bonus}%)",
                "card_name": "Спецспособность",
                "delta": special_bonus
            }
            positive_factors.append(spec_factor)
            vol_factors.append(spec_factor)

        # Оцениваем изгнанников на поверхности
        exiles_data = []
        for ex in eliminated_players:
            ex_id, ex_name, ex_cards, _ = _extract_player_data(ex)
            surv_status = is_exile_alive_on_surface(ex, catastrophe)
            ex_factors = []

            if not surv_status["is_alive_surface"]:
                ex_factors.append({
                    "title": f"Погиб на поверхности ({surv_status['reason']}) — угрозы не представляет",
                    "delta": 0,
                    "is_dead": True
                })
            else:
                if sabotage_suppressed:
                    ex_factors.append({
                        "title": f"Изгнанник {ex_name} разогнан охранным дроном «Периметр» (0%)",
                        "delta": 0,
                        "is_suppressed": True
                    })
                else:
                    for b_k in ("big_inventory", "backpack", "baggage"):
                        bag = ex_cards.get(b_k, {})
                        if bag.get("revealed", False):
                            text = _get_card_full_text(bag)
                            if any(w in text for w in ["винтовка", "карабин", "пистолет", "glock", "мачете", "ракетница", "оружие", "нож"]):
                                ex_factors.append({
                                    "title": f"Вооруженная засада: изгнанник {ex_name} атакует с оружием ({bag.get('value')}) (-15%)!",
                                    "delta": -15
                                })
                                break

                    prof = ex_cards.get("profession", {})
                    if prof.get("revealed", False):
                        if prof.get("tag") == "security":
                            ex_factors.append({
                                "title": f"Военный опыт: изгнанник {ex_name} ({prof.get('value')}) минирует подходы (-10%)!",
                                "delta": -10
                            })

                    hobby = ex_cards.get("hobby", {})
                    if hobby.get("revealed", False):
                        h_text = _get_card_full_text(hobby)
                        if any(h in h_text for h in ["охота", "бой", "бушкрафт", "выживание", "дронами"]):
                            ex_factors.append({
                                "title": f"Саботаж в руинах: {ex_name} ({hobby.get('value')}) устраивает засаду (-8%)",
                                "delta": -8
                            })

                    if not ex_factors:
                        health = ex_cards.get("health", {})
                        is_weak = False
                        if health.get("revealed", False):
                            h_val = _get_card_full_text(health)
                            if any(w in h_val for w in ["сердечная", "астма", "хромает", "диабет"]):
                                is_weak = True

                        bio = ex_cards.get("gender") or ex_cards.get("biology", {})
                        if bio.get("revealed", False) and bio.get("age", 30) >= 65:
                            is_weak = True

                        if is_weak:
                            ex_factors.append({
                                "title": f"Ослабленный изгнанник {ex_name} едва держится на ногах (0%)",
                                "delta": 0
                            })
                        else:
                            ex_factors.append({
                                "title": f"Озлобленный изгнанник {ex_name} шумит и привлекает мутантов к шлюзу (-5%)",
                                "delta": -5
                            })

            exiles_data.append({
                "id": ex_id,
                "name": ex_name,
                "is_alive_surface": surv_status["is_alive_surface"],
                "reason": surv_status["reason"],
                "factors": ex_factors
            })

        # Суммируем шанс
        vol_pos = sum(f["delta"] for f in vol_factors if f["delta"] > 0)
        vol_neg = sum(abs(f["delta"]) for f in vol_factors if f["delta"] < 0)

        exile_total_penalty = 0
        if not sabotage_suppressed:
            for ex in exiles_data:
                for f in ex["factors"]:
                    exile_total_penalty += abs(f["delta"])
            exile_total_penalty = min(30, exile_total_penalty)

        final_chance = max(10, min(95, base_chance + vol_pos - vol_neg - exile_total_penalty + pity_bonus))

        return {
            "type": "SURFACE_EVENT",
            "base_chance": base_chance,
            "final_chance": final_chance,
            "positive_factors": [f for f in vol_factors if f["delta"] > 0],
            "negative_factors": [f for f in vol_factors if f["delta"] < 0],
            "volunteer": {
                "id": vol_data[0] if vol_data else None,
                "name": vol_data[1] if vol_data else "Никто",
                "factors": vol_factors
            } if vol_data else None,
            "exiles": exiles_data
        }


def resolve_event_roll(event: dict, odds_data: dict, force_roll: Optional[int] = None) -> dict:
    """
    Проводит бросок d100 и определяет исход испытания:
    - Критический успех (roll <= 5): максимальный триумф и +5% дополнительного бонуса
    - Обычный успех (roll <= final_chance): победные очки бункеру
    - Критический провал (roll >= 96): сокрушительный сбой и -4% дополнительного штрафа
    - Обычный провал (roll > final_chance): урон бункеру + буст ключевых профессий
    """
    final_chance = odds_data.get("final_chance", 35)
    roll = force_roll if force_roll is not None else random.randint(1, 100)
    is_success = (roll <= final_chance)
    is_crit_success = is_success and (roll <= 5)
    is_crit_failure = not is_success and (roll >= 96)

    if is_success:
        outcome = event.get("on_success", {})
        score_delta = outcome.get("score_delta", 10)
        if is_crit_success:
            score_delta += 5
            title = f"⭐ КРИТИЧЕСКИЙ УСПЕХ! (Кубик: {roll})"
            desc = f"Фантастическое везение и профессионализм! {outcome.get('description', '')} (+{score_delta}% к бункеру)"
        else:
            title = outcome.get("title", "Угроза отражена! 🛡️")
            desc = outcome.get("description", "Бункер справился с испытанием!")
        boosted_tags = []
        boost_score = 0
        boost_reason = ""
    else:
        outcome = event.get("on_failure", {})
        score_delta = outcome.get("score_delta", -10)
        if is_crit_failure:
            score_delta -= 4
            title = f"💥 КРИТИЧЕСКИЙ ПРОВАЛ! (Кубик: {roll})"
            desc = f"Катастрофическая цепочка случайностей! {outcome.get('description', '')} ({score_delta}% к бункеру)"
        else:
            title = outcome.get("title", "Провал испытания! ⚠️")
            desc = outcome.get("description", "Бункер понес серьезный ущерб!")
        boosted_tags = outcome.get("boosted_tags", [])
        boost_score = outcome.get("boost_score", 8)
        boost_reason = outcome.get("boost_reason", "")

    return {
        "event_id": event["id"],
        "event_title": event["title"],
        "roll": roll,
        "chance_required": final_chance,
        "is_success": is_success,
        "is_crit_success": is_crit_success,
        "is_crit_failure": is_crit_failure,
        "score_delta": score_delta,
        "title": title,
        "description": desc,
        "boosted_tags": boosted_tags,
        "boost_score": boost_score,
        "boost_reason": boost_reason
    }


