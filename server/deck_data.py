def _extract_player_data(p):
    """Универсальное извлечение данных игрока (из объекта Player или dict)"""
    if hasattr(p, "id"):
        return p.id, p.name, p.cards, p.is_alive
    return p.get("id"), p.get("name", "Игрок"), p.get("cards", {}), p.get("is_alive", True)


def is_exile_alive_on_surface(player, catastrophe: Optional[dict] = None) -> dict:
    """
    Проверяет, жив ли изгнанный игрок на поверхности бункера.
    В экстремальных катаклизмах (-70°C, серная кислота, наномашины, метан, потоп)
    человек без специальной защиты погибает в первые же минуты.
    """
    _, name, cards, is_alive = _extract_player_data(player)
    if is_alive:
        return {"is_alive_surface": False, "reason": "Находится внутри бункера."}

    if not catastrophe:
        return {"is_alive_surface": True, "reason": "Укрылся в руинах на поверхности."}

    cat_id = catastrophe.get("id", "")
    lethality_info = EXTREME_CATASTROPHE_LETHALITY.get(cat_id)

    if not isinstance(lethality_info, dict) or lethality_info.get("level") != "EXTREME":
        return {
            "is_alive_surface": True,
            "reason": "Выжил в руинах пустоши, полон ярости и жаждет мести бункеру!"
        }

    # Проверяем открытую экипировку
    has_protection = False
    prot_item_name = ""
    req_keywords = lethality_info.get("required_keywords", [])
    if not isinstance(req_keywords, list):
        req_keywords = []

    for cat_name in ["big_inventory", "backpack", "baggage", "hobby", "fact"]:
        card = cards.get(cat_name, {})
        if isinstance(card, dict) and card.get("revealed", False):
            text = (str(card.get("value", "")) + " " + str(card.get("desc", ""))).lower()
            for kw in req_keywords:
                if kw in text:
                    has_protection = True
                    prot_item_name = str(card.get("value", "Защитное снаряжение"))
                    break
        if has_protection:
            break

    if has_protection:
        return {
            "is_alive_surface": True,
            "reason": f"Выжил снаружи благодаря «{prot_item_name}»! Озлоблен и следит за шлюзом."
        }
    else:
        death_reason = str(lethality_info.get("death_reason", "Погиб в смертоносной среде на поверхности."))
        return {
            "is_alive_surface": False,
            "reason": death_reason
        }


